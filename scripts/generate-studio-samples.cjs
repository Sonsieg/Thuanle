const fs = require('node:fs');
const path = require('node:path');
const source = path.resolve(process.argv[2] || path.join(__dirname, '../../thuanlevan-main/public/audio'));
const samples = {};
for (const instrument of ['piano', 'guitar']) {
  for (const filename of fs.readdirSync(path.join(source, instrument)).sort()) {
    if (!filename.endsWith('.mp3')) continue;
    samples[`/audio/${instrument}/${filename}`] = `data:audio/mpeg;base64,${fs.readFileSync(path.join(source, instrument, filename)).toString('base64')}`;
  }
}
const target = path.join(__dirname, '../src/studio/generated/sampleAssets.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, '// Generated by npm run studio:samples. Bundled for offline playback.\nexport const sampleAssets: Record<string, string> = ' + JSON.stringify(samples, null, 2) + ';\n');
console.log(`Bundled ${Object.keys(samples).length} piano/guitar samples.`);
